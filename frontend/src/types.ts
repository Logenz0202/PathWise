// Shapes of the data the API sends and receives; mirror backend/app/schemas.

export type TransportMode = 'car' | 'train' | 'bus'
export type FuelType = 'petrol' | 'diesel' | 'lpg' | 'electric'
export type Priority = 'balanced' | 'fastest' | 'cheapest' | 'greenest'
export type Currency = 'EUR' | 'PLN'
export type Language = 'en' | 'pl'
// Real road route from OSRM, or an estimate when routing was unavailable
export type RouteSource = 'osrm' | 'estimate'

export interface TransportOption {
  mode: TransportMode
  // Road distance for car and bus, estimated rail distance for the train
  distance_km: number
  time_minutes: number
  cost_eur: number
  co2_kg: number
}

// The Eco-Coach's structured recommendation
export interface Advice {
  recommended: TransportMode
  headline: string
  reason: string
  tips: string[]
}

// Summary shown in the history list
export interface ComparisonSummary {
  id: number
  origin: string
  destination: string
  distance_km: number
  car: TransportOption
  train: TransportOption
  bus: TransportOption
  car_name: string | null
  car_fuel_type: FuelType | null
  created_at: string
}

// Full comparison, including the car profile and the AI recommendation
export interface Comparison extends ComparisonSummary {
  // For electric cars these are kWh/100km and EUR/kWh (the names are historical)
  car_consumption_l_per_100km: number | null
  car_fuel_price_per_liter: number | null
  priority: Priority
  notes: string | null
  // Where the road distance and times came from
  route_source: RouteSource
  ai_advice: Advice
}

// Road route between two cities with door-to-door times for an average car (GET /api/geo/route)
export interface RouteInfo {
  origin: string
  destination: string
  distance_km: number
  source: RouteSource
  // [lat, lng] points along the road; null for estimates
  geometry: [number, number][] | null
  car: TransportOption
  train: TransportOption
  bus: TransportOption
}

export interface ComparisonRequest {
  origin: string
  destination: string
  // Only when the user typed their own distance; otherwise the API uses the road route
  distance_km?: number
  priority: Priority
  notes?: string
  car_name?: string
  car_fuel_type?: FuelType
  car_consumption_l_per_100km?: number
  car_fuel_price_per_liter?: number
  // Only affect the AI recommendation's wording (amounts are always EUR)
  currency: Currency
  language: Language
}

// Body of POST/PUT /api/cars
export interface CarProfileInput {
  name: string
  fuel_type: FuelType
  consumption_per_100km: number
  energy_price_eur: number
}

export interface CarProfile extends CarProfileInput {
  id: number
  created_at: string
}

// Built-in "average car" for a fuel type; looks like a saved car to the rest of the app
export interface AverageCar extends Omit<CarProfileInput, 'name'> {
  id: `avg:${FuelType}`
  isAverage: true
  name: null
}

// A car the comparison can use: a saved preset or a built-in average car
export type SelectableCar = CarProfile | AverageCar

export type CountryCode = 'PL' | 'DE' | 'CZ' | 'SK' | 'LT' | 'BY' | 'UA'

// Entry of data/cities.json (generated by scripts/build_cities.mjs)
export interface City {
  id: string
  name: string
  country: string
  code: CountryCode
  lat: number
  lng: number
  pop: number
  // 1: capitals and 400k+, 2: 150k+, 3: 50k+, 4: 15k+
  tier: 1 | 2 | 3 | 4
  isCapital: boolean
  alt?: string[]
}
